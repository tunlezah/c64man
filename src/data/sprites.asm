// ============================================================================
// CHOMPER - Sprite Data
// ============================================================================
// Each sprite is 24x21 pixels, stored as 63 bytes + 1 padding = 64 bytes
// In multicolor mode: 12x21 "fat pixels" (2 bits per pixel)
//
// Bit pairs in multicolor:
//   00 = Transparent
//   01 = Sprite multicolor 0 (black - outline)
//   10 = Sprite individual color (yellow for chomper, etc.)
//   11 = Sprite multicolor 1 (white - highlight/eyes)
//
// Sprite Layout:
//   Sprite 0: Chomper (player) - mouth open right
//   Sprite 1: Chomper mouth closed
//   Sprite 2: Chomper mouth open left
//   Sprite 3: Chomper mouth open up
//   Sprite 4: Chomper mouth open down
//   Sprite 5: Spectre (ghost) frame 1
//   Sprite 6: Spectre (ghost) frame 2
//   Sprite 7: Frightened spectre frame 1
//   Sprite 8: Frightened spectre frame 2 (flashing)
//   Sprite 9: Spectre eyes only (eaten, returning to base)
//   Sprite 10: Death animation frame 1
//   Sprite 11: Death animation frame 2
//   Sprite 12: Death animation frame 3
//   Sprite 13: Death animation frame 4
//   Sprite 14: Bonus item sprite
//   Sprite 15: Score popup (200/400/800/1600)
// ============================================================================

